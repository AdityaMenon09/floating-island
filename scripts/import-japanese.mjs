// Copies the kana and word lists from the Japanese tracker into the island's flashcards.
// Run from the island folder after the tracker's lists change:  node scripts/import-japanese.mjs
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const source = path.resolve(here, '..', '..', 'japanese-tracker', 'app.html');
const target = path.resolve(here, '..', 'src', 'renderer', 'japanese-data.js');
const html = fs.readFileSync(source, 'utf8');

// Pulls out `var NAME = [ ... ];` (the first one) and evaluates the literal on its own.
function arrayLiteral(name) {
  const start = html.indexOf(`var ${name} = [`);
  if (start < 0) throw new Error(`${name} not found in ${source}`);
  const open = html.indexOf('[', start);
  const close = html.indexOf('\n  ];', open);
  if (close < 0) throw new Error(`end of ${name} not found`);
  return vm.runInNewContext(`(${html.slice(open, close + 4)})`, {}, { timeout: 1000 });
}

const kana = arrayLiteral('KANA').map(({ h, r, s }) => ({ h, r, s }));
const words = arrayLiteral('WORDS').map(({ k, r, m, s }) => ({ k, r, m, s }));
if (kana.length < 46 || words.length < 20) throw new Error(`suspiciously short lists: ${kana.length} kana, ${words.length} words`);

fs.writeFileSync(target,
  '// Generated by scripts/import-japanese.mjs from japanese-tracker/app.html (KANA, WORDS). Don\'t edit by hand.\n' +
  `window.JP_DATA = ${JSON.stringify({ kana, words })};\n`);
console.log(`wrote ${path.relative(process.cwd(), target)}: ${kana.length} kana, ${words.length} words ` +
  `(${words.filter((w) => w.s === 'h').length} hiragana, ${words.filter((w) => w.s === 'k').length} katakana)`);
